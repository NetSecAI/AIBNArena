"""Add combined scenarios to the catalog: the faults of 2 to 4 existing scenarios at once.

A combined scenario names its components -- catalog scenarios, pinned at their version --
and a few method tuples, one method per component. The compiler binds each component as
its own family would, on draws where no two blast radii meet, and composes the task and
the oracles from the components' own (scenarios/compiler/compiler.py,
scenarios/oracle_loader.py). This script only chooses what to combine, and writes nothing
it has not first seen compile and render:

  * a component must inject a fault and be judged on reachability alone
    (`combination_blocker`): the security families and the shaped QoS family are left out,
    and the run says why;
  * a combination is checked on every topology all its components apply to (or the ones
    given with --topology), for every seed of --check-seeds: a method tuple is kept only
    if it compiles with disjoint blast radii and materializes on each of them;
  * a topology on which no tuple tried can be kept is dropped from the combination, and
    recorded as excluded in topology_applicability.json with the reason.

The output is `scenarios/combined/<n>_scenarios/<a>__<b>[__<c>[__<d>]].yaml`, one file per
combination, filed by how many scenarios it joins, and one entry per file in
`scenarios/topology_applicability.json`. Choices are seeded:
the same arguments write the same files. A file rewritten with different content takes
the next minor version, so results judged on the old one stay distinguishable.

    python -m scenarios.generator.combine_scenarios                 # 2, 3 and 4 faults
    python -m scenarios.generator.combine_scenarios --sizes 2 --per-size 3 --topology campus_small
    python -m scenarios.generator.combine_scenarios \\
        --combination disable_interface,vlan_misconfiguration --methods 4
    python -m scenarios.generator.combine_scenarios --dry-run
"""
from __future__ import annotations

