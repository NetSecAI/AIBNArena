import itertools
import json
import random
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable

REPOSITORY_ROOT = Path(__file__).resolve().parents[2]
if str(REPOSITORY_ROOT) not in sys.path:
    sys.path.insert(0, str(REPOSITORY_ROOT))

import yaml  # noqa: E402

from scenarios.access import CompiledScenarioInstance  # noqa: E402
from scenarios.compiler.compiler import ScenarioCompiler  # noqa: E402
from scenarios.compiler.loader import (  # noqa: E402
    APPLICABILITY_FILENAME,
    COMBINED_DOMAIN,
    combination_blocker,
    discover_scenarios,
    load_topology_applicability,
    load_yaml,
    scenario_applies_to_topology,
    validate_scenario,
)

GENERATED_HEADER = (
    "# Generated by scenarios/generator/combine_scenarios.py: regenerate it rather than edit it.\n"
    "# The faults of every component go in together, on draws where no two blast radii meet;\n"
    "# the oracles are composed from the components' own when it is compiled.\n"
)
ORACLES = {
    "healthy": "scenarios/oracles/combined/healthy-v1.yaml",
    "expected_degradation": "scenarios/oracles/combined/expected-degradation-v1.yaml",
    "repair": "scenarios/oracles/combined/repair-v1.yaml",
    "preservation": "scenarios/oracles/combined/preservation-v1.yaml",
}
MIN_SIZE, MAX_SIZE = 2, 4
#: The vaguest wording of every combination: one generic sentence, whatever is combined.
#: The medium and high wordings are not written: the compiler concatenates the
#: components' own, each rendered with its own draw.
LOW_WORDING = "Something on this network is not working the way it should. Put it back."
VERSION = re.compile(r"[0-9]+(\.[0-9]+)*")


@dataclass(frozen=True)
class Family:
    """A catalog scenario that may be a component."""

    domain: str
    source: str  # relative to the catalog root, e.g. connectivity/remove_ip.yaml
    name: str
    version: str
    method_ids: tuple[int, ...]
    method_names: dict[int, str] = field(hash=False)
    variants: tuple[str, ...] = ()
    base_variant: str | None = None


@dataclass
class Outcome:
    name: str
    families: tuple[Family, ...]
    tuples: list[tuple[int, ...]] = field(default_factory=list)
    topologies: list[str] = field(default_factory=list)
    excluded: dict[str, str] = field(default_factory=dict)
    reason: str | None = None


class Checker:
    """Compiles and materializes candidate tuples, one compiler per topology and seed."""

    def __init__(self, root: Path, topologies: dict[str, Path], seeds: Iterable[int]):
        from benchmarks.platforms.containerlab.compiled_topology import CompiledContainerLabTopology

        self.root = root
        self.seeds = list(seeds)
        self.compilers = {
            (topology, seed): ScenarioCompiler.from_topology_file(path, seed=seed)
            for topology, path in topologies.items()
            for seed in self.seeds
        }
        self.materializers = {}
        for topology, path in topologies.items():
            document = load_yaml(path)
            environment = (document.get("topology") or {}).get("environment") or {}
            self.materializers[topology] = (
                CompiledContainerLabTopology(document) if environment.get("type") == "containerlab" else None)
        self.cache: dict[tuple[str, str, tuple[int, ...]], str | None] = {}

    def failure(self, topology: str, document: dict[str, Any], picks: tuple[int, ...]) -> str | None:
        """Why the tuple cannot be kept on the topology, or None when every seed binds it."""
        key = (topology, document["scenario"], picks)
        if key not in self.cache:
            self.cache[key] = self._failure(topology, document, picks)
        return self.cache[key]

    def _failure(self, topology: str, document: dict[str, Any], picks: tuple[int, ...]) -> str | None:
        probe = {**document, "methods": [{"id": 1, "name": "probe", "components": list(picks)}]}
        for seed in self.seeds:
            compiler = self.compilers[(topology, seed)]
            try:
                tasks = compiler.compile_scenario(COMBINED_DOMAIN, probe, scenarios_root=self.root)
            except ValueError as exc:
                return f"seed {seed}: {exc}"
            materializer = self.materializers[topology]
            if materializer is None:
                return "the topology has no containerlab environment to render the faults on"
            try:
                materializer.materialize(CompiledScenarioInstance(tasks[0]))
            except Exception as exc:  # noqa: BLE001 - any refusal to render rejects the tuple
                return f"seed {seed}: does not render ({type(exc).__name__}: {exc})"
        return None


def catalog_families(root: Path) -> tuple[list[Family], dict[str, str]]:
    """Every scenario that may be a component, and why each other one may not."""
    families, refused = [], {}
    for domain, path, payload in discover_scenarios(root):
        source = f"{domain}/{path.name}"
        if domain == COMBINED_DOMAIN:
            continue
        blocker = combination_blocker(domain, payload)
        if blocker:
            refused[source] = blocker
            continue
        task = payload.get("task")
        families.append(Family(
            domain=domain,
            source=source,
            name=str(payload["scenario"]),
            version=str(payload["version"]),
            method_ids=tuple(int(m["id"]) for m in payload["methods"]),
            method_names={int(m["id"]): str(m["name"]) for m in payload["methods"]},
            variants=tuple(str(name) for name in task) if isinstance(task, dict) else (),
            base_variant=(str(payload["base_variant"]) if payload.get("base_variant") else None),
        ))
    families.sort(key=lambda family: (family.domain, family.name))
    return families, refused


def size_folder(size: int) -> str:
    """The folder of `combined/` holding the combinations of `size` scenarios."""
    return f"{size}_scenarios"


def combined_name(families: Iterable[Family]) -> str:
    return "__".join(family.name for family in families)


def base_variant(families: tuple[Family, ...]) -> str:
    """The wording every component shares, preferring the components' own base."""
    shared = [name for name in families[0].variants if all(name in f.variants for f in families[1:])]
    if not shared:
        raise ValueError(f"{combined_name(families)}: the components declare no wording in common")
    bases = {f.base_variant for f in families}
    if len(bases) == 1 and next(iter(bases)) in shared:
        return str(next(iter(bases)))
    return shared[0]


def combination_path(combined_dir: Path, families: tuple[Family, ...]) -> Path:
    return combined_dir / size_folder(len(families)) / f"{combined_name(families)}.yaml"


def previous_methods(path: Path) -> tuple[dict[tuple[int, ...], int], list[dict[str, Any]]]:
    """The ids a file already gives its tuples, and the tuples withdrawn from it."""
    if not path.exists():
        return {}, []
    previous = load_yaml(path)
    ids = {tuple(method["components"]): int(method["id"]) for method in previous.get("methods") or []}
    return ids, list((previous.get("combination") or {}).get("withdrawn") or [])


def method_ids(tuples: list[tuple[int, ...]], previous: dict[tuple[int, ...], int],
               withdrawn: list[dict[str, Any]]) -> list[int]:
    """A tuple the file already lists keeps its id; a new one takes an id never used in it,
    so a task id never comes to name a different set of faults."""
    taken = set(previous.values()) | {int(item["id"]) for item in withdrawn}
    following = max(taken, default=0) + 1
    ids = []
    for picks in tuples:
        if picks in previous:
            ids.append(previous[picks])
        else:
            ids.append(following)
            following += 1
    return ids


def scenario_document(families: tuple[Family, ...], tuples: list[tuple[int, ...]],
                      version: str, seed: int, check_seeds: int, *,
                      previous: dict[tuple[int, ...], int] | None = None,
                      withdrawn: list[dict[str, Any]] | None = None) -> dict[str, Any]:
    withdrawn = list(withdrawn or [])
    ids = method_ids(tuples, previous or {}, withdrawn)
    combination: dict[str, Any] = {
        "blast_radius": "disjoint",
        "components": [
            {"source": f.source, "scenario": f.name, "version": f.version} for f in families
        ],
        "generator": {"seed": seed, "check_seeds": check_seeds},
    }
    if withdrawn:
        combination["withdrawn"] = withdrawn
    return {
        "schema_version": "0.1",
        "version": version,
        "oracles": {phase: {"path": path, "version": "1.0.0"} for phase, path in ORACLES.items()},
        "scenario": combined_name(families),
        "task": {"low": LOW_WORDING},
        "base_variant": base_variant(families),
        "success_criteria": {"all_of": [{"type": "lab_connectivity"}]},
        "combination": combination,
        "methods": sorted((
            {
                "id": index,
                "name": "+".join(f.method_names[pick] for f, pick in zip(families, picks)),
                "components": list(picks),
            }
            for index, picks in zip(ids, tuples)), key=lambda method: method["id"]),
    }


def render_yaml(document: dict[str, Any]) -> str:
    """The catalog's own layout: flow mappings for references, one method per item."""
    def flow(mapping: dict[str, Any]) -> str:
        return "{" + ", ".join(f"{key}: {scalar(value)}" for key, value in mapping.items()) + "}"

    def scalar(value: Any) -> str:
        if isinstance(value, list):
            return "[" + ", ".join(scalar(item) for item in value) + "]"
        if isinstance(value, bool) or value is None:
            return json.dumps(value)
        if isinstance(value, (int, float)):
            return str(value)
        text = str(value)
        # Versions are quoted, as everywhere in the catalog; anything YAML would not
        # read back as the same string is quoted too.
        if VERSION.fullmatch(text) or yaml.safe_load(text) != text or any(c in text for c in ":{}[],#&*!|>'\"%@`"):
            return json.dumps(text)
        return text

    lines = [GENERATED_HEADER.rstrip("\n")]
    lines.append(f'schema_version: "{document["schema_version"]}"')
    lines.append(f'version: "{document["version"]}"')
    lines.append("oracles:")
    for phase, reference in document["oracles"].items():
        lines.append(f"  {phase}: {flow(reference)}")
    lines.append(f"scenario: {document['scenario']}")
    lines.append("# medium and high: the components' own wordings, concatenated at compile time.")
    lines.append("task:")
    for variant, text in document["task"].items():
        lines.append(f"  {variant}: >-")
        lines.append(f"    {text}")
    lines.append(f"base_variant: {document['base_variant']}")
    lines.append("success_criteria:")
    lines.append("  all_of:")
    for criterion in document["success_criteria"]["all_of"]:
        lines.append(f"    - {flow(criterion)}")
    combination = document["combination"]
    lines.append("combination:")
    lines.append(f"  blast_radius: {combination['blast_radius']}")
    lines.append("  components:")
    for component in combination["components"]:
        lines.append(f"    - {flow(component)}")
    lines.append(f"  generator: {flow(combination['generator'])}")
    if combination.get("withdrawn"):
        lines.append("  # Tuples a check refused: never proposed again, their ids never reused.")
        lines.append("  withdrawn:")
        for item in combination["withdrawn"]:
            lines.append(f"    - id: {item['id']}")
            if "name" in item:
                lines.append(f"      name: {item['name']}")
            lines.append(f"      components: {scalar(item['components'])}")
            lines.append("      reason: >-")
            lines.append(f"        {item['reason']}")
    lines.append("methods:")
    for method in document["methods"]:
        lines.append(f"  - id: {method['id']}")
        lines.append(f"    name: {method['name']}")
        lines.append(f"    components: {scalar(method['components'])}")
    text = "\n".join(lines) + "\n"
    if yaml.safe_load(text) != document:  # the layout must not change what the file says
        raise AssertionError(f"{document['scenario']}: rendered YAML does not read back as written")
    return text


def next_version(path: Path, document: dict[str, Any]) -> str:
    """1.0.0 for a new file; the same version for the same content; the next minor otherwise."""
    if not path.exists():
        return "1.0.0"
    previous = load_yaml(path)
    current = str(previous.get("version", "1.0.0"))

    def comparable(payload: dict[str, Any]) -> dict[str, Any]:
        stripped = json.loads(json.dumps(payload))
        stripped.pop("version", None)
        (stripped.get("combination") or {}).pop("generator", None)
        return stripped

    if comparable(previous) == comparable(document):
        return current
    major, minor, _ = (int(part) for part in current.split("."))
    return f"{major}.{minor + 1}.0"


def plan_combination(families: tuple[Family, ...], *, checker: Checker, applicability: dict[str, Any],
                     requested: list[str], all_topologies: list[str], methods: int,
                     max_tuples: int, seed: int,
                     withdrawn: frozenset[tuple[int, ...]] = frozenset()) -> Outcome:
    name = combined_name(families)
    outcome = Outcome(name=name, families=families)
    excluded: dict[str, str] = {}
    candidates = []
    for topology in all_topologies:
        missing = [f.source for f in families
                   if not scenario_applies_to_topology(applicability, f.source, topology)]
        if missing:
            excluded[topology] = (f"{', '.join(missing)} does not apply to this topology "
                                  "(scenarios/topology_applicability.json).")
        elif topology not in requested:
            excluded[topology] = "Not checked: the generator was not asked for this topology."
        else:
            candidates.append(topology)
    if not candidates:
        outcome.reason = "no requested topology that every component applies to"
        outcome.excluded = excluded
        return outcome

    probe_document = scenario_document(families, [tuple(f.method_ids[0] for f in families)],
                                       "1.0.0", seed, len(checker.seeds))
    product = list(itertools.product(*(f.method_ids for f in families)))
    random.Random(f"{seed}:{name}").shuffle(product)
    # Dropped after the shuffle, so a withdrawal moves no other tuple's place in the order.
    product = [picks for picks in product if picks not in withdrawn]
    tested: list[tuple[tuple[int, ...], set[str], dict[str, str]]] = []
    accepted: list[tuple[int, ...]] = []
    for picks in product[:max_tuples]:
        binds, reasons = set(), {}
        for topology in candidates:
            failure = checker.failure(topology, probe_document, picks)
            if failure is None:
                binds.add(topology)
            else:
                reasons[topology] = failure
        tested.append((picks, binds, reasons))
        if binds >= set(candidates):
            accepted.append(picks)
            if len(accepted) == methods:
                break

    kept = list(candidates)
    if not accepted:
        # No tuple binds everywhere: drop, one at a time, the topology the fewest tuples
        # bind on, until some tuple covers what is left.
        while kept and not accepted:
            counts = {t: sum(1 for _, binds, _ in tested if t in binds) for t in kept}
            weakest = min(kept, key=lambda t: (counts[t], -kept.index(t)))
            sample = next((reasons[weakest] for _, _, reasons in tested if weakest in reasons), "")
            excluded[weakest] = (f"No method tuple of the {len(tested)} tried binds here with disjoint "
                                 f"blast radii on every check seed and renders"
                                 + (f"; first refusal: {sample}" if sample else "."))
            kept.remove(weakest)
            accepted = [picks for picks, binds, _ in tested if binds >= set(kept)][:methods] if kept else []
    if not accepted:
        outcome.reason = "no method tuple binds with disjoint blast radii on any requested topology"
        outcome.excluded = excluded
        return outcome
    outcome.tuples = accepted
    outcome.topologies = kept
    outcome.excluded = {t: excluded[t] for t in all_topologies if t in excluded}
    return outcome


def resolve_families(spec: str, families: list[Family]) -> tuple[Family, ...]:
    by_key = {**{f.name: f for f in families}, **{f.source: f for f in families}}
    picked = []
    for item in (part.strip() for part in spec.split(",") if part.strip()):
        if item not in by_key:
            raise SystemExit(f"--combination: {item!r} is not a combinable scenario "
                             f"(known: {', '.join(sorted(f.name for f in families))})")
        picked.append(by_key[item])
    if not MIN_SIZE <= len(set(picked)) <= MAX_SIZE or len(set(picked)) != len(picked):
        raise SystemExit(f"--combination {spec!r}: name {MIN_SIZE} to {MAX_SIZE} distinct scenarios")
    return tuple(sorted(picked, key=lambda f: (f.domain, f.name)))


def parser() -> argparse.ArgumentParser:
    arguments = argparse.ArgumentParser(
        description="Add combined scenarios (2 to 4 existing faults injected together) to the catalog.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    arguments.add_argument("--scenarios", type=Path, default=REPOSITORY_ROOT / "scenarios",
                           help="catalog root")
    arguments.add_argument("--sizes", type=int, nargs="+", default=[2, 3, 4],
                           help="how many scenarios each combination joins (2 to 4)")
    arguments.add_argument("--per-size", default="5",
                           help="combinations written per size, or 'all'")
    arguments.add_argument("--methods", type=int, default=3,
                           help="method tuples (one method per component) per combination")
    arguments.add_argument("--families", nargs="+", default=None,
                           help="only combine these scenarios (names or catalog paths)")
    arguments.add_argument("--combination", action="append", default=[],
                           help="an explicit combination, comma-separated (repeatable); "
                                "replaces the sampling")
    arguments.add_argument("--topology", action="append", default=[],
                           help="topologies to check and declare (repeatable; default: every one "
                                "in the applicability map)")
    arguments.add_argument("--check-seeds", type=int, default=10,
                           help="a tuple is kept only if it binds for every seed 0..N-1")
    arguments.add_argument("--max-tuples", type=int, default=48,
                           help="method tuples tried per combination before giving up")
    arguments.add_argument("--seed", type=int, default=0, help="seed of the generator's own choices")
    arguments.add_argument("--clean", action="store_true",
                           help="remove previously generated combinations this run does not write")
    arguments.add_argument("--dry-run", action="store_true", help="print the plan, write nothing")
    return arguments


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    root = args.scenarios.resolve()
    if any(not MIN_SIZE <= size <= MAX_SIZE for size in args.sizes):
        raise SystemExit(f"--sizes takes values from {MIN_SIZE} to {MAX_SIZE}")
    if args.methods < 1 or args.check_seeds < 1 or args.max_tuples < 1:
        raise SystemExit("--methods, --check-seeds and --max-tuples must be positive")
    per_size = None if str(args.per_size).lower() == "all" else int(args.per_size)

    applicability = load_topology_applicability(root)
    topology_dir = root / "topologies"
    all_topologies = list(applicability.get("topologies") or {}) or sorted(
        path.stem for path in topology_dir.glob("*.yaml"))
    requested = args.topology or all_topologies
    unknown = sorted(set(requested) - set(all_topologies))
    if unknown:
        raise SystemExit(f"--topology: unknown {unknown} (known: {all_topologies})")

    families, refused = catalog_families(root)
    if args.families:
        wanted = set(args.families)
        families = [f for f in families if f.name in wanted or f.source in wanted]
        missing = wanted - {f.name for f in families} - {f.source for f in families}
        if missing:
            raise SystemExit(f"--families: not combinable or unknown: {sorted(missing)}")
    print(f"combinable scenarios ({len(families)}): " + ", ".join(f.source for f in families))
    for source, reason in sorted(refused.items()):
        print(f"  left out {source}: {reason}")

    checker = Checker(root, {t: topology_dir / f"{t}.yaml" for t in requested}, range(args.check_seeds))
    plan_options = dict(checker=checker, applicability=applicability, requested=requested,
                        all_topologies=all_topologies, methods=args.methods,
                        max_tuples=args.max_tuples, seed=args.seed)
    combined_dir = root / COMBINED_DOMAIN

    def plan(combo: tuple[Family, ...]) -> Outcome:
        _, withdrawn = previous_methods(combination_path(combined_dir, combo))
        return plan_combination(combo, withdrawn=frozenset(tuple(item["components"]) for item in withdrawn),
                                **plan_options)

    outcomes: list[Outcome] = []
    if args.combination:
        for spec in args.combination:
            outcomes.append(plan(resolve_families(spec, families)))
    else:
        for size in sorted(set(args.sizes)):
            pool = list(itertools.combinations(families, size))
            random.Random(f"{args.seed}:size{size}").shuffle(pool)
            written = 0
            for combo in pool:
                if per_size is not None and written >= per_size:
                    break
                outcome = plan(combo)
                outcomes.append(outcome)
                written += outcome.reason is None
            if per_size is not None and written < per_size:
                print(f"  size {size}: only {written} of the {per_size} asked for could be kept")

    entries = applicability.setdefault("scenarios", {})
    kept_files = set()
    for outcome in outcomes:
        if outcome.reason:
            print(f"skip {outcome.name}: {outcome.reason}")
            continue
        path = combination_path(combined_dir, outcome.families)
        previous, withdrawn = previous_methods(path)
        document = scenario_document(outcome.families, outcome.tuples, "1.0.0", args.seed, args.check_seeds,
                                     previous=previous, withdrawn=withdrawn)
        document["version"] = next_version(path, document)
        relative = path.relative_to(root).as_posix()
        kept_files.add(relative)
        print(f"{'would write' if args.dry_run else 'write'} {relative} v{document['version']}: "
              f"{len(outcome.tuples)} method tuple(s) on {', '.join(outcome.topologies)}")
        for method in document["methods"]:
            print(f"    m{method['id']} {method['components']} {method['name']}")
        if args.dry_run:
            continue
        validate_scenario(COMBINED_DOMAIN, document, path)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render_yaml(document), encoding="utf-8")
        entries[relative] = {
            "scenario": outcome.name,
            "generated_by": "scenarios/generator/combine_scenarios.py",
            "components": [f.source for f in outcome.families],
            "topologies": outcome.topologies,
            "excluded": outcome.excluded,
            "note": (f"{len(outcome.families)} faults injected together, one per component, on "
                     "draws where no two blast radii meet. Each method tuple listed in the file "
                     f"compiled and rendered on every topology above for seeds 0-{args.check_seeds - 1}."),
        }

    if args.clean:
        # Every combination this run did not write: declared in the map, or only on disk.
        stale = {relative for relative in entries
                 if relative.startswith(f"{COMBINED_DOMAIN}/") and relative not in kept_files}
        stale |= {path.relative_to(root).as_posix() for path in combined_dir.rglob("*.yaml")} - kept_files
        for relative in sorted(stale):
            print(f"{'would remove' if args.dry_run else 'remove'} {relative}")
            if not args.dry_run:
                (root / relative).unlink(missing_ok=True)
                entries.pop(relative, None)
    if not args.dry_run:
        (root / APPLICABILITY_FILENAME).write_text(
            json.dumps(applicability, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    kept = sum(1 for o in outcomes if not o.reason)
    print(f"{kept} combination(s) {'planned' if args.dry_run else 'written'}, "
          f"{len(outcomes) - kept} skipped")
    return 0


